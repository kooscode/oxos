#!/usr/bin/env python3
"""Turn the boot splash (kernel/splash/splash.png: 640x480, 8-bit palette) into a C++ header for the ISO launcher:
the palette (256 x 0x00RRGGBB) and the pixels' palette indices, row after row, as a raw deflate stream (RFC 1951; the
launcher unpacks it with the kernel's inflater, kernel/include/xk/inflate.h).
usage: gen_splash.py SPLASH.png OUT.h
"""
import struct
import sys
import zlib


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG")
    pos, idat, palette, header = 8, b"", None, None
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", chunk)
        elif kind == b"PLTE":
            palette = chunk
        elif kind == b"IDAT":
            idat += chunk
    w, h, depth, colour, _, _, interlace = header
    if (depth, colour, interlace) != (8, 3, 0) or palette is None:
        sys.exit(f"{path}: needs an 8-bit palette PNG, not interlaced")
    raw, rows, prev = zlib.decompress(idat), [], bytearray(w)
    for y in range(h):
        f, line = raw[y * (w + 1)], bytearray(raw[y * (w + 1) + 1:(y + 1) * (w + 1)])
        for x in range(w):
            a = line[x - 1] if x else 0
            b, c = prev[x], prev[x - 1] if x else 0
            if f == 1:
                line[x] = (line[x] + a) & 0xFF
            elif f == 2:
                line[x] = (line[x] + b) & 0xFF
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 0xFF
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 0xFF
        rows.append(bytes(line))
        prev = line
    colours = [palette[i:i + 3] for i in range(0, len(palette), 3)]
    colours += [b"\0\0\0"] * (256 - len(colours))
    return w, h, [(r << 16) | (g << 8) | b for r, g, b in colours], b"".join(rows)


def main():
    w, h, palette, pixels = read_png(sys.argv[1])
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    packed = c.compress(pixels) + c.flush()
    out = [f"// Generated by gen_splash.py from {sys.argv[1].split('/')[-1]}: do not edit.",
           "#pragma once", "", f"constexpr int SplashWidth = {w}, SplashHeight = {h};",
           "constexpr unsigned SplashPalette[256] = {"]
    for i in range(0, 256, 8):
        out.append("    " + ", ".join(f"0x{c:06X}" for c in palette[i:i + 8]) + ",")
    out += ["};", f"constexpr unsigned SplashPackedSize = {len(packed)};", "constexpr unsigned char SplashPacked[] = {"]
    for i in range(0, len(packed), 24):
        out.append("    " + ",".join(str(b) for b in packed[i:i + 24]) + ",")
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print(f"{sys.argv[2]}: {w}x{h}, {len(packed)} bytes packed")


if __name__ == "__main__":
    main()
