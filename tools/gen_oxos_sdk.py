#!/usr/bin/env python3
"""Generate the kernel extension SDK's import definitions from the kernel's export table (spec/oxos_internal/34 §9).

usage: gen_oxos_sdk.py EXPORTS_TSV OUT_DEF

OUT_DEF (oxos_sdk/lib/xboxkrnl.def) lists every export of xboxkrnl.exe by ordinal, with the symbol the compiler gives
a call to it (stdcall _Name@N, fastcall @Name@N; cdecl functions, the compiler's helpers and variables by their C
name, to which `lld-link /lib` adds the underscore), for `lld-link /lib /def:` to turn into the import library
extensions link with (oxos_sdk/Makefile). Debugger-only rows (kind "debug") are left out, as in the kernel's own .def.
"""
import sys

HEADER = "; Generated by tools/gen_oxos_sdk.py from kernel/exports.tsv. Do not edit; regenerate.\n"


def decorated(name, convention, arg_bytes, kind):
    """The symbol of one export in the .def, as `lld-link /lib` reads it for i386."""
    if kind == "data":
        return name
    if convention == "stdcall":
        return f"_{name}@{arg_bytes}"
    if convention == "fastcall":
        return f"@{name}@{arg_bytes}"
    return name  # cdecl (DbgPrint, the Rtl*printf functions, memcpy, ...) and compiler helpers (_alldiv, ...)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.split("\n\n")[1])
    tsv, out = sys.argv[1:3]
    lines = [HEADER + "LIBRARY xboxkrnl.exe", "EXPORTS"]
    for line in open(tsv).read().splitlines()[1:]:
        ordinal, name, convention, arg_bytes, kind = line.split("\t")[:5]
        if kind == "debug":
            continue
        entry = decorated(name, convention.split("/")[0], arg_bytes, kind)
        lines.append(f"    {entry:<44} @{int(ordinal)} NONAME{' DATA' if kind == 'data' else ''}")
    text = "\n".join(lines) + "\n"
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    open(out, "w").write(text)


if __name__ == "__main__":
    main()
