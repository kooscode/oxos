CONVENTION = {"stdcall": "NTAPI", "fastcall": "FASTCALL", "cdecl": "__cdecl"}
NOT_POINTER_TYPES = {"PS_STATISTICS"}  # names that start with P but are structures (process statistics), not pointers
INTERNAL = {"OXOSWriteExtensionLog"}  # the SDK's own plumbing (oxos_log), declared where the SDK uses it
# OXOS's exports for the dashboard's own tools that no extension should call (they erase the hard disk): not declared for extensions.
NOT_FOR_EXTENSIONS = {"OXOSFormatDisk", "OXOSDeleteAllPartitions"}


def decorated(name, convention, arg_bytes, kind):
    """The symbol of one export in the .def, as `lld-link /lib` reads it for i386."""
    if kind == "data":
        return name
    if convention == "stdcall":
        return f"_{name}@{arg_bytes}"
    if convention == "fastcall":
        return f"@{name}@{arg_bytes}"
    return name  # cdecl (DbgPrint, the Rtl*printf functions, memcpy, ...) and compiler helpers (_alldiv, ...)


def kernel_declarations(src):
    """name -> (return type, parameter list) of every XBAPI function the kernel declares or defines."""
    out = {}
    for path in sorted(glob.glob(os.path.join(src, "**", "*.h"), recursive=True) + glob.glob(os.path.join(src, "**", "*.cpp"), recursive=True)):
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r"^XBAPI\s+([^;{]*?\))\s*[;{]", text, re.S | re.M):
            d = " ".join(m.group(1).split())
            d = re.sub(r"\[\[[^\]]*\]\]|__attribute__\(\([^)]*\)\)", "", d).strip()
            f = re.match(r"(.*?)\s*\b(?:NTAPI|FASTCALL|__cdecl|__stdcall|__fastcall)?\s*\b([A-Za-z_]\w*)\s*\((.*)\)$", d)
            if f and f.group(2) not in out:
                out[f.group(2)] = (f.group(1).strip(), f.group(3).strip())
    # Functions written in assembly carry their prototype in the comment above them: "// void NTAPI RtlUnwind(PVOID TargetFrame, ...)".
    for path in sorted(glob.glob(os.path.join(src, "**", "*.S"), recursive=True)):
        for m in re.finditer(r"^//\s*([A-Za-z_][\w *]*?)\s+(?:NTAPI|FASTCALL)\s+([A-Za-z_]\w*)\(([^)]*)\)", open(path, encoding="utf-8").read(), re.M):
            out.setdefault(m.group(2), (m.group(1).strip(), " ".join(m.group(3).split())))
    return out


def routine_typedefs(src):
    """name -> typedef line of the kernel's function-pointer types (PKDEFERRED_ROUTINE, PIO_APC_ROUTINE, ...)."""
    out = {}
    for path in sorted(glob.glob(os.path.join(src, "**", "*.h"), recursive=True)):
        for m in re.finditer(r"^typedef\s+([^;()]+?)\s*\(\s*(NTAPI|FASTCALL)?\s*\*\s*(P\w+)\s*\)\s*\(([^;]*)\);", open(path, encoding="utf-8").read(), re.M):
            params = " ".join(m.group(4).split()) or "void"
            out.setdefault(m.group(3), f"typedef {m.group(1)}({m.group(2) or ''} *{m.group(3)})({params});".replace("( *", "(*"))
    return out


def type_names(text):
    """(identifier, used through a pointer) for the type names in a declaration: parameter names and struct tags left out."""
    names = []
    for part in text.split(","):
        part = re.sub(r"\[[^\]]*\]", "", part).strip()
        part = re.sub(r"/\*.*?\*/", "", part)  # a commented-out name (PVOID /*Lock*/)
        part = re.sub(r"\bstruct\s+\w+", "VOID", part)  # a tag (struct _KDPC *Dpc): the structure is declared by its plain name
        tokens = re.findall(r"[A-Za-z_]\w*|\*", part)
        words = [t for t in tokens if t != "*"]
        if len(words) >= 2 and words[-1] not in KNOWN and tokens[-1] != "*":
            tokens = tokens[:len(tokens) - 1 - tokens[::-1].index(words[-1])] + tokens[len(tokens) - tokens[::-1].index(words[-1]):]  # the parameter's name
        for i, t in enumerate(tokens):
            if t != "*":
                names.append((t, i + 1 < len(tokens) and tokens[i + 1] == "*"))
    return names


def table_check(header):
    names = re.findall(r"^OXOS_IMPORT [^;(]*?\b(\w+)\(", header, re.M)
    return "\n".join(["// SPDX-License-Identifier: MIT",
                      "// Generated by tools/gen_oxos_sdk.py: the address of every kernel function oxos_kernel.h declares. sdk/Makefile links it against the import",
                      "// library, so a prototype that does not match its export fails the SDK's build. Do not edit; regenerate.",
                      "#include <oxos_kernel.h>", "", "__declspec(dllexport) void oxos_kernel_table_check(const void **Out) {"] +
                     [f"    Out[{i}] = (const void *)&{n};" for i, n in enumerate(names)] + ["}", ""])


def c_library(src):
    """The kernel's C library as kernel/src/runtime/c_library.h declares it: (names, its declarations and comments for extensions)."""
    text = open(os.path.join(src, "runtime", "c_library.h"), encoding="utf-8").read()
    body = text[text.index('extern "C" {') + len('extern "C" {'):text.rindex("#ifdef __cplusplus")].strip("\n")
    lines = [line for line in body.split("\n") if line.strip() not in ("}", "#endif")]
    body = "\n".join(lines).strip("\n")
    names = re.findall(r"XK_C\((\w+)\)", body)
    body = re.sub(r" \(\w+\.cpp(?:, \w+\.cpp)*\)", "", re.sub(r"XK_C\((\w+)\)", r"\1", body)).replace("__builtin_va_list", "va_list")
    return names, body


def c_library_source(src):
    """kernel/src/runtime/c_library_extensions.cpp for the SDK: plain names, the SDK's header."""
    text = open(os.path.join(src, "runtime", "c_library_extensions.cpp"), encoding="utf-8").read()
    text = text[text.index("#include"):]
    text = text.replace("#include <runtime/c_library.h>", "#include <oxos_kernel.h>")
    text = re.sub(r"XK_C\((\w+)\)", r"\1", text)
    return ("// SPDX-License-Identifier: MIT\n"
            "// Generated by tools/gen_oxos_sdk.py from the OXOS kernel's kernel/src/runtime/c_library_extensions.cpp: the C functions the kernel does\n"
            "// not have itself, in the SDK's library (oxos_kernel.h declares them with the kernel's). Do not edit; regenerate.\n" + text)


def kernel_header(rows, decls, routines, c_names, c_declarations):
    functions, missing = [], []
    for ordinal, name, convention, arg_bytes, kind in rows:
        if kind != "func" or convention.split("/")[0] not in CONVENTION or name in c_names:
            continue
        if name in INTERNAL or name in NOT_FOR_EXTENSIONS or name.startswith("oxos_"):
            continue  # the SDK's own plumbing, or one of the kernel's functions oxos_sdk.h declares under an oxos_ name (kernel_symbol)
        if name not in decls:
            missing.append(name)
            continue
        functions.append((int(ordinal), name, CONVENTION[convention.split("/")[0]], *decls[name]))
    if missing:
        sys.exit(f"gen_oxos_sdk.py: no XBAPI declaration in the kernel for {', '.join(missing)}")

    # The types the prototypes use: function-pointer types copied from the kernel (each after the ones it uses), the rest opaque structures. PNAME is the
    # pointer type of the structure NAME, by the kernel's convention (but for NOT_POINTER_TYPES).
    routine_order, opaque = [], {}

    def need(names, chain=()):
        for t, through_pointer in names:
            if t in KNOWN or t in routine_order or t in chain:
                continue
            if t in routines:
                text = routines[t]
                need(type_names(re.search(r"\)\((.*)\);$", text).group(1)) + type_names(text.split("(")[0][len("typedef "):]), chain + (t,))
                routine_order.append(t)
            elif not t.startswith("P") or t in NOT_POINTER_TYPES:
                opaque.setdefault(t, set())
            else:
                opaque.setdefault(t[1:], set()).add(t)

    for f in functions:
        need(type_names(f[3]) + type_names(f[4]))

    lines = ["// SPDX-License-Identifier: MIT",
             "// oxos_kernel.h: the Xbox kernel's functions for OXOS kernel extensions, generated by tools/gen_oxos_sdk.py from the OXOS kernel's own declarations.",
             "// Do not edit; regenerate. oxos_sdk.h includes it: an extension calls any of these by name (NtOpenFile(...)), and hooks one with",
             "// oxos_hook(NtOpenFile, MyHook) (oxos_sdk.h). C17 and C++20.",
             "#pragma once", "", BASE_TYPES.rstrip(), "",
             "// --- Kernel objects: the functions take and return pointers to them; their contents are the kernel's own", ""]
    for base, names in sorted(opaque.items()):
        lines.append(f"typedef struct _{base} {base}" + "".join(f", *{p}" for p in sorted(names)) + ";")
    lines += ["", "// --- Counts and kinds passed by value", "", "typedef LONG " + ", ".join(SCALAR_TYPES[:7]) + ",",
              "    " + ", ".join(SCALAR_TYPES[7:]) + ";", "", "// --- Routines the kernel calls back", ""]
    lines += [routines[t] for t in routine_order]
    lines += ["", "// --- Functions", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", "#define OXOS_IMPORT __declspec(dllimport)", ""]
    for ordinal, name, cc, ret, params in sorted(functions, key=lambda f: f[1].lower()):
        lines.append(f"OXOS_IMPORT {ret} {cc} {name}({params or 'void'});")
    lines += ["", "// --- The C library: the kernel's own (OXOS's exports 402-405 and 417-439), as OXOS's own code uses it. Plain C names, not hookable.", "",
              c_declarations, "",
              "// Data: milliseconds since the console started (it counts up by one each millisecond, and wraps after 49 days).",
              "OXOS_IMPORT extern volatile ULONG KeTickCount;", "", "#ifdef __cplusplus", "}", "#endif", ""]
    return "\n".join(lines)


def write(path, text):
    try:
        if open(path).read() == text:
            return
    except OSError:
        pass
    open(path, "w").write(text)


def main():
    if len(sys.argv) != 7:
        sys.exit(__doc__.split("\n\n")[1])
    tsv, src, out_def, out_h, out_check, out_c_library = sys.argv[1:7]
    rows = [line.split("\t")[:5] for line in open(tsv).read().splitlines()[1:]]
    lines = [DEF_HEADER + "LIBRARY oxoskrnl.exe", "EXPORTS"]
    for ordinal, name, convention, arg_bytes, kind in rows:
        if kind == "debug":
            continue
        entry = decorated(name, convention.split("/")[0], arg_bytes, kind)
        lines.append(f"    {entry:<44} @{int(ordinal)} NONAME{' DATA' if kind == 'data' else ''}")
    write(out_def, "\n".join(lines) + "\n")
    header = kernel_header(rows, kernel_declarations(src), routine_typedefs(src), *c_library(src))
    write(out_h, header)
    write(out_check, table_check(header))
    write(out_c_library, c_library_source(src))


if __name__ == "__main__":
    main()
