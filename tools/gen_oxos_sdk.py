#!/usr/bin/env python3
"""Generate the kernel extension SDK's kernel files from the kernel's sources (spec/oxos_internal/34 §9).

usage: gen_oxos_sdk.py EXPORTS_TSV KERNEL_SRC OUT_DEF OUT_KERNEL_H OUT_CHECK OUT_C_LIBRARY

OUT_DEF (sdk/src/oxoskrnl.def) lists every export of oxoskrnl.exe (the OXOS kernel) by ordinal, with the symbol the compiler gives a call to it (stdcall
_Name@N, fastcall @Name@N; cdecl functions, the compiler's helpers and variables by their C name, to which `lld-link /lib` adds the underscore), for `lld-link
/lib /def:` to turn into the import library extensions link with (sdk/Makefile). Debugger-only rows (kind "debug") are left out, as in the kernel's own .def.

OUT_KERNEL_H (sdk/include/oxos_kernel.h) declares every kernel function an extension can call, with the prototype the kernel itself declares (its XBAPI
declarations under KERNEL_SRC) and the types those prototypes need. OUT_CHECK (sdk/src/kernel_table_check.c) takes the address of every function OUT_KERNEL_H
declares: the SDK's build links it against the import library, so a prototype whose arguments do not add up to the export's size (stdcall _Name@N) fails there,
not in an extension. OUT_C_LIBRARY (sdk/src/oxos_c_library.cpp) is the kernel's kernel/src/runtime/c_library_extensions.cpp: the C functions the kernel
does not have itself, which the SDK's library carries instead. The SDK stays self-contained: these files are committed.
"""
