#!/usr/bin/env python3
"""Generate kernel/src/hal/screenfont.inc: a 6x10 bitmap font (ASCII 0x20-0x7E) for the kernel's on-screen log
(network-log builds, spec/oxos-internal/03 §10), rendered from DejaVu Sans Mono (Bitstream Vera / DejaVu licence,
free to embed). Each glyph is 10 rows; bit 5 of a row is the leftmost pixel.

  gen_screen_font.py [--font PATH] [--out FILE]
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

W, H = 6, 10


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")
    ap.add_argument("--out", default="kernel/src/hal/screenfont.inc")
    a = ap.parse_args()
    font = ImageFont.truetype(a.font, 10)
    rows_out = []
    for code in range(0x20, 0x7F):
        img = Image.new("L", (W * 4, H * 4), 0)
        ImageDraw.Draw(img).text((0, -1), chr(code), font=font, fill=255)
        glyph = []
        for y in range(H):
            bits = 0
            for x in range(W):
                if img.getpixel((x, y)) >= 96:
                    bits |= 0x20 >> x
            glyph.append(bits)
        rows_out.append(glyph)
    with open(a.out, "w") as f:
        f.write("// Generated by tools/gen_screen_font.py from DejaVu Sans Mono: 6x10 glyphs for ASCII 0x20-0x7E.\n")
        f.write("static const unsigned char HalpScreenFont[95][10] = {\n")
        for code, g in zip(range(0x20, 0x7F), rows_out):
            f.write("    {" + ", ".join(f"0x{b:02X}" for b in g) + "}, // " + repr(chr(code)) + "\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
