#!/usr/bin/env python3
"""Pick the Xbox CPU's microcode updates out of Intel's published microcode files (the Makefile's input).

usage: mkucode.py OUT.inc FILE...

Each FILE is an Intel microcode data file (intel-ucode/06-08-xx from Intel's Linux microcode repository): a series
of updates, each a 48-byte header and its data (2048 bytes in all for these old ones). The updates for platform 4
(platform-flag bit 0x10, the one the Xbox's Pentium III reports) are written to OUT.inc, unmodified, as a C++
initializer of 32-bit words, one update per {...}. The kernel picks one by signature and platform at start-up.
"""
import struct, sys


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__.split("\n\n")[1])
    out, files = sys.argv[1], sys.argv[2:]
    lines = []
    for name in files:
        data = open(name, "rb").read()
        o = 0
        while o + 48 <= len(data):
            hv, rev, date, sig, ck, lv, pf, dsize, tsize = struct.unpack_from("<9I", data, o)
            tsize = tsize or 2048
            if hv != 1 or tsize != 2048 or o + tsize > len(data):
                sys.exit(f"{name}: unexpected update at offset {o:#x}")
            if sum(struct.unpack_from("<512I", data, o)) & 0xFFFFFFFF:
                sys.exit(f"{name}: bad checksum at offset {o:#x}")
            if pf & 0x10:
                words = struct.unpack_from("<512I", data, o)
                body = ",".join(f"{w:#x}" for w in words)
                lines.append(f"// signature {sig:#x}, revision {rev}, date {date:08x}, platforms {pf:#x}\n{{{body}}},")
            o += tsize
    if not lines:
        sys.exit("no update for platform 4")
    with open(out, "w") as f:
        f.write("// Generated by tools/mkucode.py from Intel's microcode files (third_party/intel-ucode). Do not edit.\n")
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
